import { readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';

// The registry foundation currently contains an orphaned demo fragment. Keep
// the downloaded source untouched and remove only that invalid fragment here.
export async function buildBeautifulUI() {
  const source = await readFile(new URL('../src/beautiful-ui/upstream/foundation.css', import.meta.url), 'utf8');
  const css = source.replace('  .records-footer-hint {\n    display: none;\n  }\n}', '')
    .replace(':root {', ':host {')
    .replaceAll('.dark', ':host-context(.dark)')
    .replace('@import "tailwindcss";', '@import "tailwindcss" source(none);\n@source "../ChatComposer.js";\n@source "../Section.js";\n@source "../ApprovalCard.js";\n@source "../ThinkingState.js";\n@source "../Button.js";');
  const input = new URL('../src/beautiful-ui/upstream/build.css', import.meta.url);
  await writeFile(input, css);
  execFileSync('pnpm', ['exec', 'tailwindcss', '-i', input.pathname, '-o', new URL('../src/beautiful-ui/generated.css', import.meta.url).pathname, '--minify'], { stdio: 'inherit' });
  const compiled = await readFile(new URL('../src/beautiful-ui/generated.css', import.meta.url), 'utf8');
  await writeFile(new URL('../src/beautiful-ui/foundation.generated.js', import.meta.url), `// Generated by scripts/build-beautiful-ui.mjs; do not edit.\nexport default ${JSON.stringify(compiled)};\n`);
}
